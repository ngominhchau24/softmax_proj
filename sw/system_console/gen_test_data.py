#!/usr/bin/env python3
"""gen_test_data.py - write smx_test_data.tcl for smx_demo.tcl.

Each test case is a row set (X as packed 32-bit words, little-endian, 4 elements per word) and the
expected Y from the golden model (model/softmax_ref.py, bit-exact with the RTL). The Tcl demo runs
the cases on the board over JTAG and compares Y, so the board needs no softmax code of its own.

Usage (from the repo root):  python3 sw/system_console/gen_test_data.py [P] [N_SEG]
P and N_SEG must match the bitstream (default 8 8 = the submitted configuration).
"""
import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "model"))
import softmax_ref as ref  # noqa: E402

P = int(sys.argv[1]) if len(sys.argv) > 1 else 8
N_SEG = int(sys.argv[2]) if len(sys.argv) > 2 else 8
rng = random.Random(20261107)


def clip(v):
    return max(-128, min(127, int(round(v))))


def gauss_row(n, sigma):
    return [clip(rng.gauss(0, sigma)) for _ in range(n)]


def unif_row(n):
    return [rng.randint(-128, 127) for _ in range(n)]


# (name, L, K, rows)
cases = []
cases.append(("example_L10", 10, 5909, [[10, -5, 3, 0, -20, 7, 1, -8, 12, 40]]))
cases.append(("L1_saturates_to_255", 1, 5909, [[5]]))
cases.append(("K0_uniform_L64", 64, 0, [unif_row(64), unif_row(64)]))
cases.append(("one_hot_extreme_L100", 100, 65535, [[127] + [-128] * 99]))
cases.append(("all_min_L33_K65535", 33, 65535, [[-128] * 33, [127] * 33]))
cases.append(("deit_L197_R2", 197, 5909, [gauss_row(197, 30), gauss_row(197, 30)]))
cases.append(("deit_L197_S0p02", 197, 1891, [gauss_row(197, 60)]))
cases.append(("max_row_L512", 512, 1891, [unif_row(512)]))
cases.append(("rows16_L37", 37, 18910, [gauss_row(37, 40) for _ in range(16)]))
cases.append(("tail_L9_P_plus_1", P + 1, 12000, [unif_row(P + 1) for _ in range(3)]))

lines = [
    "# smx_test_data.tcl - GENERATED by gen_test_data.py (P = %d, N_SEG = %d). Do not edit by hand." % (P, N_SEG),
    "# Each case: {name len rows k {x words per row} {expected y per row}}",
    "set SMX_DATA_P %d" % P,
    "set SMX_DATA_N_SEG %d" % N_SEG,
    "set SMX_CASES {}",
]
for name, L, K, rows in cases:
    assert 1 <= L <= 512 and 1 <= len(rows) <= 16 and all(len(r) == L for r in rows)
    xs, ys = [], []
    for r in rows:
        nw = (L + 3) // 4
        b = bytes((v & 255) for v in r) + bytes(nw * 4 - L)
        xs.append("{" + " ".join("0x%08X" % w for w in struct.unpack("<%dI" % nw, b)) + "}")
        y, _ = ref.softmax_row(r, K, P=P, n_seg=N_SEG)
        ys.append("{" + " ".join(str(v) for v in y) + "}")
    lines.append("lappend SMX_CASES [list {%s} %d %d %d {%s} {%s}]" % (name, L, len(rows), K, " ".join(xs), " ".join(ys)))

out = os.path.join(HERE, "smx_test_data.tcl")
with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out, "with", len(cases), "cases")
