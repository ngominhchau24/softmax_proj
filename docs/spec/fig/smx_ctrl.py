"""smx_ctrl structure at P = 8. The state machine is in smx_fsm. Run: python3 docs/spec/fig/smx_ctrl.py"""
from schematic import Sheet

s = Sheet("smx_ctrl", 1270, 560)
s.boundary(130, 10, 1000, 530, "smx_ctrl")

s.box(220, 180, 140, 100, "state_q", "8 states")
s.box(480, 60, 90, 40, "g_q")
s.box(480, 130, 90, 40, "r_q")
s.box(480, 370, 90, 40, "yg_q")
s.box(220, 430, 130, 60, "group geometry", "from len - 1")
s.box(680, 60, 110, 50, "g == last")
s.box(680, 130, 110, 70, "r == rows - 1")
s.box(920, 60, 130, 190, "output decode")
s.box(920, 290, 130, 40, "{r, g}")
s.box(920, 360, 130, 40, "{r, yg}")

s.wire([(20, 200), (220, 200)], "start")
s.wire([(20, 220), (220, 220)], "sum_last")
s.wire([(20, 240), (220, 240)], "div_done")
s.wire([(20, 260), (220, 260)], "y_last")
s.wire([(20, 460), (220, 460)], "len[9:0]")
s.wire([(20, 510), (730, 510), (730, 200)], "rows[4:0]")
s.wire([(20, 400), (480, 400)], "y_valid")
s.wire([(360, 200), (420, 200), (420, 80), (480, 80)], "step")
s.dot(420, 150)
s.wire([(420, 150), (480, 150)])
s.wire([(360, 270), (420, 270), (420, 380), (480, 380)], "clear")
s.wire([(570, 80), (680, 80)], "g_q[5:0]")
s.dot(580, 80)
s.wire([(580, 80), (580, 300), (920, 300)], "g_q[5:0]", at=1, lx=650)
s.wire([(570, 150), (680, 150)], "r_q[3:0]", lx=595)
s.dot(590, 150)
s.wire([(590, 150), (590, 320), (920, 320)], "r_q[3:0]", at=1, lx=650)
s.dot(800, 320)
s.wire([(800, 320), (800, 370), (920, 370)])
s.wire([(570, 390), (920, 390)], "yg_q[5:0]")
s.wire([(350, 450), (640, 450), (640, 100), (680, 100)], "g_last_idx[7:0]", lx=430)
s.wire([(350, 480), (880, 480), (880, 230), (920, 230)], "en_last[7:0]", lx=430)
s.wire([(790, 90), (920, 90)], "is_last_grp")
s.dot(880, 90)
s.wire([(880, 90), (880, 30), (290, 30), (290, 180)])
s.wire([(790, 180), (920, 180)], "is_last_row")
s.dot(900, 180)
s.wire([(900, 180), (900, 20), (320, 20), (320, 180)])
s.wire([(360, 240), (920, 240)], "state_q", lx=430)
for name, y in [("grp_valid", 80), ("grp_pass2", 100), ("grp_first", 120), ("grp_last", 140), ("grp_en[7:0]", 160),
                ("div_start", 180), ("run_done", 200)]:
    s.wire([(1050, y), (1250, y)], name, lx=1150, port=True)
s.wire([(1050, 310), (1250, 310)], "grp_addr[9:0]", lx=1150, port=True)
s.wire([(1050, 380), (1250, 380)], "y_wr_addr[9:0]", lx=1150, port=True)
s.note(460, 532, "Every output is combinational from state and registers. Drawn at P = 8. clk and rst_n are not drawn.")
s.save(__file__)
