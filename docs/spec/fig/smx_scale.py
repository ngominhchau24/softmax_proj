"""smx_scale, one lane: u = q*K, c = ceil(u / 2^16). Run: python3 docs/spec/fig/smx_scale.py"""
from schematic import Sheet

s = Sheet("smx_scale", 1200, 400)
s.boundary(130, 30, 960, 340, "smx_scale")
s.note(170, 56, "stage 1")
s.note(510, 56, "stage 2")
s.note(880, 56, "stage 3")

s.box(170, 80, 100, 40, "s1_q_q")
s.box(170, 180, 100, 40, "s1_k_q")
s.box(350, 80, 90, 140, "multiplier", "8 x 17 signed")
s.box(510, 130, 100, 40, "s2_prod_q")
s.box(680, 190, 120, 60, "ceil", "hi + (lo != 0)")
s.box(880, 70, 100, 40, "s3_u_q")
s.box(880, 200, 100, 40, "s3_c_q")
s.box(170, 300, 100, 40, "s1_vld_q")
s.box(510, 300, 100, 40, "s2_vld_q")
s.box(880, 300, 100, 40, "vld_q")

s.wire([(20, 100), (170, 100)], "q_in[7:0]")
s.wire([(20, 200), (170, 200)], "{1'b0, k_in[15:0]}")
s.wire([(270, 100), (350, 100)], "s1_q_q[7:0]")
s.wire([(270, 200), (350, 200)], "s1_k_q[16:0]")
s.wire([(440, 150), (510, 150)], "prod[24:0]")
s.wire([(610, 150), (640, 150), (640, 90), (880, 90)], "s2_prod_q[24:0]", at=2, lx=660)
s.dot(640, 150)
s.wire([(640, 150), (640, 220), (680, 220)])
s.wire([(800, 220), (880, 220)], "c_comb[8:0]")
s.wire([(980, 90), (1180, 90)], "u_out[24:0]", lx=1100, port=True)
s.wire([(980, 220), (1180, 220)], "c_out[8:0]", lx=1100, port=True)
s.wire([(20, 320), (170, 320)], "in_valid")
s.wire([(270, 320), (510, 320)])
s.wire([(610, 320), (880, 320)])
s.wire([(980, 320), (1180, 320)], "out_valid", lx=1100, port=True)
s.note(520, 366, "Latency SCALE_LAT = 3. clk and rst_n are not drawn.")
s.save(__file__)
